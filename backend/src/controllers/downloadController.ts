import { Request, Response } from 'express';
import JSZip from 'jszip';

export const downloadTerraformProject = async (req: Request, res: Response) => {
  try {
    const { terraformCode, projectName, blueprint } = req.body;

    if (typeof terraformCode !== "string" || !terraformCode.trim()) {
      return res.status(400).json({ error: "No code provided to download." });
    }

    // Keep user-provided names safe for ZIP paths, generated Terraform strings,
    // and the Content-Disposition response header.
    const requestedName = typeof projectName === "string" ? projectName : "";
    const safeProjectName = requestedName
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-zA-Z0-9_-]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 64) || "aws-infra-project";

    const zip = new JSZip();
    const rootFolder = zip.folder(safeProjectName);

    // 1. main.tf (The heavy lifting)
    rootFolder?.file("main.tf", 
      `# Generated by CloudArchitect AI\n# Project: ${safeProjectName}\n\n${terraformCode}`
    );

    // 2. variables.tf (Standardized variables)
    rootFolder?.file("variables.tf", `
variable "region" {
  description = "AWS Region"
  type        = string
  default     = "us-east-1"
}

variable "project_name" {
  description = "Project Name"
  type        = string
  default     = "${safeProjectName}"
}
    `);

    // 3. outputs.tf (Placeholders for after deployment)
    rootFolder?.file("outputs.tf", `
output "vpc_id" {
  value = "Check AWS Console after terraform apply"
}
    `);

    // 4. README.md (Professional instructions)
    rootFolder?.file("README.md", `
# ${safeProjectName} Infrastructure
Generated by CloudArchitect Agentic AI.

## How to Deploy
1. Install Terraform CLI.
2. Run \`terraform init\` to download providers.
3. Run \`terraform plan\` to preview changes.
4. Run \`terraform apply\` to build your cloud!
    `);

    // Generate ZIP buffer
    const content = await zip.generateAsync({ type: "nodebuffer" });

    // Set headers for file download
    res.set({
      'Content-Type': 'application/zip',
      'Content-Disposition': `attachment; filename="${safeProjectName}.zip"`,
      'Content-Length': content.length
    });

    return res.send(content);

  } catch (error) {
    console.error("Download Error:", error);
    return res.status(500).json({ error: "Failed to generate ZIP file." });
  }
};